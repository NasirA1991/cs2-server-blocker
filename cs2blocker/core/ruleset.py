"""Deterministic firewall plan and nftables ruleset generation.

The generated text is the only thing the privileged helper feeds to ``nft``.
It always targets exactly one table, ``inet cs2blocker``, and never contains
another table name or a flush statement.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import replace as dataclass_replace

from .model import FirewallPlan, Mode, Pop, Protocol, SdrSnapshot, Selection
from .regions import REGION_ORDER
from .util import format_ranges, merge_ranges, nft_comment

TABLE_NAME = "cs2blocker"
DEFAULT_GENERATED_AT = "1970-01-01T00:00:00+00:00"


def _region_rank(pop: Pop) -> int:
    try:
        return REGION_ORDER.index(pop.region)
    except ValueError:
        return len(REGION_ORDER)


def build_plan(snapshot: SdrSnapshot, selection: Selection) -> FirewallPlan:
    """Resolve a selection against a snapshot into the exact POPs to block."""
    known = snapshot.pops
    selected = set(selection.pops)
    unknown = sorted(selected - set(known))
    warnings: list[str] = []
    if unknown:
        warnings.append(f"selection contains unknown POP(s): {', '.join(unknown)}")

    if selection.mode is Mode.BLOCK:
        blocked_codes = selected & set(known)
    else:
        blocked_codes = set(known) - selected

    selected_ips: set[str] = set()
    if selection.mode is Mode.ONLY:
        for code in selected & set(known):
            selected_ips.update(r.address for r in known[code].relays)

    blocked: list[Pop] = []
    for code in sorted(blocked_codes):
        pop = known[code]
        relays = pop.relays
        if selection.mode is Mode.ONLY and selected_ips:
            filtered = tuple(r for r in relays if r.address not in selected_ips)
            removed = len(relays) - len(filtered)
            if removed:
                warnings.append(
                    f"{code}: {removed} relay address(es) shared with a selected POP "
                    "were left unblocked to keep the selected POP working"
                )
            relays = filtered
        if not relays:
            continue
        blocked.append(dataclass_replace(pop, relays=relays))

    for code in sorted(selected & set(known)):
        if not known[code].relays:
            warnings.append(f"selected POP {code} has no relay endpoints")

    blocked.sort(key=lambda p: (_region_rank(p), p.code))
    blocked_codes_final = {p.code for p in blocked}
    allowed = tuple(sorted(set(known) - blocked_codes_final))

    if selection.mode is Mode.BLOCK and not selected:
        warnings.append("no POPs selected; the firewall table will be cleared")
    if selection.mode is Mode.ONLY:
        allowed_with_relays = sum(1 for code in allowed if known[code].relays)
        if not blocked:
            warnings.append("selection allows every known POP; nothing will be blocked")
        elif allowed_with_relays == 0:
            warnings.append(
                "selection blocks every known POP; matchmaking is likely to fail"
            )
        elif allowed_with_relays <= 2:
            warnings.append(
                f"selection leaves only {allowed_with_relays} POP(s) allowed; "
                "matchmaking may fail or take very long"
            )
    elif len(blocked) == sum(1 for pop in known.values() if pop.relays):
        warnings.append("all POPs with relay endpoints are blocked; matchmaking may fail")

    port_ranges = (
        merge_ranges((r.port_start, r.port_end) for pop in blocked for r in pop.relays)
        if selection.protocol is Protocol.UDP
        else ()
    )
    if selection.protocol is Protocol.UDP and blocked and not port_ranges:
        warnings.append("blocked POPs have no usable SDR port ranges")

    return FirewallPlan(
        mode=selection.mode,
        protocol=selection.protocol,
        block_forward=selection.block_forward,
        selected=frozenset(selection.pops),
        blocked=tuple(blocked),
        allowed=allowed,
        port_ranges=port_ranges,
        warnings=tuple(warnings),
        revision=snapshot.revision,
    )


def _header(plan: FirewallPlan, *, version: str, generated_at: str, revision: int) -> str:
    selected = ",".join(sorted(plan.selected)) or "-"
    blocked = ",".join(plan.blocked_codes) or "-"
    return (
        f"# Generated by cs2blocker {nft_comment(version, max_len=32)} at "
        f"{nft_comment(generated_at, max_len=40)}\n"
        f"# revision={revision} mode={plan.mode.value} protocol={plan.protocol.value} "
        f"selected={selected} blocked={blocked}\n"
        "# Apply with: cs2blockctl apply   (only inet cs2blocker is touched)\n"
    )


def _element_lines(pop: Pop, *, protocol: Protocol) -> tuple[list[str], list[str]]:
    v4: list[str] = []
    v6: list[str] = []
    for relay in pop.relays:
        port = "udp " if protocol is Protocol.UDP else ""
        comment = nft_comment(f"{pop.code} relay {port}{relay.port_text}", max_len=80)
        line = f'{relay.address} comment "{comment}"'
        (v4 if relay.version == 4 else v6).append(line)
    return v4, v6


def _set_block(
    name: str,
    family: str,
    comment: str,
    elements: Iterable[str],
    *,
    indent: str = "\t",
) -> list[str]:
    items = list(elements)
    lines = [
        f"{indent}set {name} {{",
        f"{indent}\ttype {family}_addr",
        f"{indent}\tflags interval",
        f'{indent}\tcomment "{nft_comment(comment)}"',
    ]
    if items:
        lines.append(f"{indent}\telements = {{")
        for index, item in enumerate(items):
            suffix = "," if index < len(items) - 1 else ""
            lines.append(f"{indent}\t\t{item}{suffix}")
        lines.append(f"{indent}\t}}")
    lines.append(f"{indent}}}")
    return lines


def _rule_line(pop: Pop, *, family: str, protocol: Protocol, forward: bool) -> str:
    set_name = f"pop_{pop.code}" if family == "ip" else f"pop_{pop.code}_v6"
    match = f"{family} daddr @{set_name}"
    if protocol is Protocol.UDP:
        match = f"udp dport @sdr_ports {match}"
    suffix = " (forward)" if forward else ""
    comment = nft_comment(
        f"cs2blocker: drop {pop.code} relay {'UDP' if protocol is Protocol.UDP else 'traffic'}{suffix}"
    )
    return (
        f"\t\t{match} counter name cnt_{pop.code} drop "
        f'comment "{comment}"'
    )


def render_nft(
    plan: FirewallPlan,
    *,
    revision: int = 0,
    replace_strategy: str = "destroy",
    version: str = "0.1.0",
    generated_at: str = DEFAULT_GENERATED_AT,
) -> str:
    """Render a complete, self-contained nftables file for our table."""
    if replace_strategy not in {"destroy", "delete", "none"}:
        raise ValueError(f"invalid replace strategy: {replace_strategy}")
    if not plan.has_rules:
        return render_clear(replace_strategy=replace_strategy, version=version, generated_at=generated_at)

    lines = [_header(plan, version=version, generated_at=generated_at, revision=revision)]
    if replace_strategy == "destroy":
        lines.append(f"destroy table inet {TABLE_NAME}")
    elif replace_strategy == "delete":
        lines.append(f"delete table inet {TABLE_NAME}")
    lines.append(f"table inet {TABLE_NAME} {{")

    if plan.protocol is Protocol.UDP:
        lines.extend(
            [
                "\tset sdr_ports {",
                "\t\ttype inet_service",
                "\t\tflags interval",
                '\t\tcomment "CS2 SDR relay UDP ports (derived from Valve data)"',
                f"\t\telements = {{ {format_ranges(plan.port_ranges)} }}",
                "\t}",
            ]
        )

    for pop in plan.blocked:
        lines.append("")
        lines.extend(
            [
                f"\tcounter cnt_{pop.code} {{",
                f'\t\tcomment "{nft_comment(f"cs2blocker drops for {pop.code}")}"',
                "\t}",
            ]
        )
        v4, v6 = _element_lines(pop, protocol=plan.protocol)
        if v4:
            lines.extend(
                _set_block(
                    f"pop_{pop.code}",
                    "ipv4",
                    f"{pop.code} {pop.name} [{pop.region.value}]",
                    v4,
                )
            )
        if v6:
            lines.extend(
                _set_block(
                    f"pop_{pop.code}_v6",
                    "ipv6",
                    f"{pop.code} {pop.name} [{pop.region.value}] (IPv6)",
                    v6,
                )
            )

    lines.extend(
        [
            "",
            "\tchain output {",
            "\t\ttype filter hook output priority filter; policy accept;",
        ]
    )
    for pop in plan.blocked:
        if pop.ipv4_relays:
            lines.append(_rule_line(pop, family="ip", protocol=plan.protocol, forward=False))
        if pop.ipv6_relays:
            lines.append(_rule_line(pop, family="ip6", protocol=plan.protocol, forward=False))
    lines.append("\t}")

    if plan.block_forward:
        lines.extend(
            [
                "",
                "\tchain forward {",
                "\t\ttype filter hook forward priority filter; policy accept;",
            ]
        )
        for pop in plan.blocked:
            if pop.ipv4_relays:
                lines.append(_rule_line(pop, family="ip", protocol=plan.protocol, forward=True))
            if pop.ipv6_relays:
                lines.append(_rule_line(pop, family="ip6", protocol=plan.protocol, forward=True))
        lines.append("\t}")

    lines.append("}")
    return "\n".join(lines) + "\n"


def render_clear(
    *,
    replace_strategy: str = "destroy",
    version: str = "0.1.0",
    generated_at: str = DEFAULT_GENERATED_AT,
) -> str:
    if replace_strategy == "none":
        return ""
    if replace_strategy not in {"destroy", "delete"}:
        raise ValueError(f"invalid replace strategy: {replace_strategy}")
    return (
        f"# Generated by cs2blocker {nft_comment(version, max_len=32)} at "
        f"{nft_comment(generated_at, max_len=40)}\n"
        f"{replace_strategy} table inet {TABLE_NAME}\n"
    )


def summarize(plan: FirewallPlan) -> str:
    if not plan.has_rules:
        return "no rules (table will be cleared)"
    parts = [f"mode={plan.mode.value}", f"blocked={len(plan.blocked)} POP(s)"]
    if plan.protocol is Protocol.UDP:
        parts.append(f"udp ports={format_ranges(plan.port_ranges)}")
    else:
        parts.append("protocol=all")
    parts.append(f"relays={plan.relay_count}")
    return ", ".join(parts)
