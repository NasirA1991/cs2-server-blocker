#!/usr/bin/env python3
"""Generate ``cs2blocker/gui/map_data.py`` from Natural Earth 1:110m land.

The generated module is checked in, so the application has no runtime
dependency on a GIS stack. Natural Earth data is public domain:
https://www.naturalearthdata.com/about/terms-of-use/
"""
from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson"
OUT = Path(__file__).resolve().parent.parent / "cs2blocker/gui/map_data.py"


def load() -> dict:
    cache = Path("/tmp/ne_110m_land.geojson")
    if not cache.is_file():
        urllib.request.urlretrieve(URL, cache)
    return json.loads(cache.read_text(encoding="utf-8"))


def rings(document: dict):
    for feature in document["features"]:
        geometry = feature["geometry"]
        polygons = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
        for polygon in polygons:
            for ring in polygon:
                points = [(round(float(lon), 2), round(float(lat), 2)) for lon, lat, *_ in ring]
                if not points or max(lat for _lon, lat in points) < -55:
                    continue  # Antarctica is outside the useful server-view window.
                yield tuple(points)


def main() -> int:
    document = load()
    data = tuple(rings(document))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as handle:
        handle.write('"""Natural Earth 1:110m land rings (public domain).\n\n')
        handle.write("Generated by scripts/build_map_data.py; do not edit by hand.\n")
        handle.write("Coordinates are (longitude, latitude), WGS84.\n")
        handle.write('"""\n\n')
        handle.write("WORLD_LAND_RINGS: tuple[tuple[tuple[float, float], ...], ...] = (\n")
        for ring in data:
            handle.write("    (\n")
            for point in ring:
                handle.write(f"        ({point[0]:.2f}, {point[1]:.2f}),\n")
            handle.write("    ),\n")
        handle.write(")\n")
    total = sum(len(r) for r in data)
    print(f"wrote {len(data)} rings, {total} points to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
